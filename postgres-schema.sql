CREATE TABLE IF NOT EXISTS users(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username TEXT UNIQUE NOT NULL, email TEXT UNIQUE NOT NULL, nickname TEXT NOT NULL, avatar TEXT NOT NULL DEFAULT '', password TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS sessions(token TEXT PRIMARY KEY,user_id INTEGER REFERENCES users(id) ON DELETE CASCADE,expires DOUBLE PRECISION NOT NULL);
CREATE TABLE IF NOT EXISTS crews(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name TEXT NOT NULL,description TEXT NOT NULL,code TEXT UNIQUE NOT NULL,owner_id INTEGER REFERENCES users(id));
CREATE TABLE IF NOT EXISTS members(crew_id INTEGER REFERENCES crews(id),user_id INTEGER REFERENCES users(id),PRIMARY KEY(crew_id,user_id));
CREATE TABLE IF NOT EXISTS challenges(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,crew_id INTEGER REFERENCES crews(id),name TEXT NOT NULL,goal INTEGER NOT NULL,start TEXT NOT NULL,"end" TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS participants(challenge_id INTEGER REFERENCES challenges(id),user_id INTEGER REFERENCES users(id),PRIMARY KEY(challenge_id,user_id));
CREATE TABLE IF NOT EXISTS runs(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,challenge_id INTEGER REFERENCES challenges(id),user_id INTEGER REFERENCES users(id),date TEXT NOT NULL,distance DOUBLE PRECISION NOT NULL,minutes DOUBLE PRECISION NOT NULL,note TEXT NOT NULL,created DOUBLE PRECISION NOT NULL);
CREATE TABLE IF NOT EXISTS resets(token TEXT PRIMARY KEY,user_id INTEGER REFERENCES users(id),expires DOUBLE PRECISION NOT NULL);
CREATE INDEX IF NOT EXISTS runs_challenge_date ON runs(challenge_id,date);
CREATE INDEX IF NOT EXISTS sessions_expiry ON sessions(expires);
CREATE TABLE IF NOT EXISTS auth_buckets(key TEXT PRIMARY KEY,attempts INTEGER NOT NULL,expires DOUBLE PRECISION NOT NULL);
